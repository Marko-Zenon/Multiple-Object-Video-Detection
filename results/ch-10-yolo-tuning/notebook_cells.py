def cell(cell_type: str, cell_id: str, source: str) -> dict:
    lines = source.splitlines(keepends=True)
    out = {"cell_type": cell_type, "id": cell_id, "metadata": {}, "source": lines}
    if cell_type == "code":
        out.update(execution_count=None, outputs=[])
    return out


def main() -> int:
    raw = NOTEBOOK.read_bytes().replace(b"\r\n", b"\n")
    notebook = json.loads(raw)
    if any(c.get("id") in IDS for c in notebook["cells"]):
        print("CH-10 section already present; nothing changed")
        return 0
    before = len(notebook["cells"])
    notebook["cells"] += [
        cell("markdown", IDS[0], SUMMARY),
        cell("code", IDS[1], CODE),
        cell("markdown", IDS[2], TODOS),
    ]
    text = json.dumps(notebook, indent=1, ensure_ascii=False) + "\n"
    NOTEBOOK.write_text(text, encoding="utf-8", newline="\n")
    print(f"appended 3 cells: {before} -> {len(notebook['cells'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
